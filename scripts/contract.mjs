#!/usr/bin/env node
/**
 * Generate the machine-readable block contract from the manifests (single source: packages/blocks/src).
 *
 *   packages/blocks/schemas/<model>.v<version>.schema.json   JSON Schema 2020-12 per content model (not per variant)
 *   packages/blocks/contract.json                            models, blocks (item ids), places, variants, binding format
 *   docs/fields.json, docs/fields.md                         fields summary: every model path and the blocks/places drawing it
 *
 *   node --experimental-strip-types --import ./scripts/ts-ext-register.mjs scripts/contract.mjs
 *   node … scripts/contract.mjs --check   # fail if any generated file is stale (run by `bun run verify`)
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ui } from "../packages/blocks/src/content/en.ts";
import { BLOCKS, FIELD_BUDGET_MAX, FIELD_BUDGET_MIN, defaultVariantId, fieldBudget } from "../packages/blocks/src/manifest/index.ts";
import { modelPaths, toJsonSchema } from "../packages/blocks/src/model/index.ts";
import { MODELS, modelKey } from "../packages/blocks/src/models/index.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const label = (key) => ui.fields[key] ?? key;
/** places drawing a path; a list path is drawn by the item place that repeats over it */
const drawnBy = (b, path) => b.places.filter((p) => p.fields.includes(path) || (p.role === "item" && p.each === path));
const schemaFile = (m) => `schemas/${m.id}.v${m.version}.schema.json`;

const binding = {
  placeAttribute: "data-place",
  fieldAttribute: "data-field",
  pointer: "RFC 6901 JSON Pointer into props; a place drawing several values lists them space-separated",
  listIndex: "* in a template is the list index; data-field carries the concrete index of the rendered instance",
  select: '[data-field~="/members/1/title"]',
  styling: "data-slot / data-role / data-shape are theme hooks, never bindings",
};

const contract = {
  $comment: "Generated by scripts/contract.mjs from packages/blocks/src. Do not edit.",
  version: 1,
  instance: {
    shape: "{ id, item, variant, options?, props }",
    item: "block type id (blocks[].item)",
    options: "instance options of the item (blocks[].options), defaults apply when absent",
    props: "content valid for the block's model",
  },
  modes: { default: "wireframe", wireframe: "rectangle-only (feed, catalog, any render without a mode)", page: "builder preview only, set explicitly" },
  imageSrc: "https://… absolute URL or /root-relative path; http:, //host, bare relative paths and javascript:/vbscript:/data: are rejected",
  binding,
  models: Object.fromEntries(
    MODELS.map((m) => [
      modelKey(m),
      {
        id: m.id,
        version: m.version,
        schema: schemaFile(m),
        paths: modelPaths(m.fields).map(({ path, field }) => ({
          path,
          type: field.type,
          required: field.required === true,
          label: label(field.label),
          ...("maxLength" in field ? { maxLength: field.maxLength } : {}),
          ...(field.type === "list" ? { record: field.item.id, minItems: field.minItems, maxItems: field.maxItems } : {}),
        })),
      },
    ]),
  ),
  blocks: BLOCKS.map((b) => ({
    item: b.id,
    category: b.category,
    label: b.label,
    model: modelKey(b.model),
    fieldBudget: fieldBudget(b),
    places: b.places,
    variants: b.variants.map((v) => ({ id: v.id, layout: v.layout, ...(v.default ? { default: true } : {}) })),
    options: Object.fromEntries(Object.entries(b.options).map(([k, d]) => [k, { ...d, label: ui.options[d.label] ?? d.label }])),
    defaultVariant: defaultVariantId(b),
  })),
};

// ---- fields summary (docs) ----
const fields = {
  $comment: "Generated by scripts/contract.mjs from the manifests. Do not edit.",
  fieldBudget: { min: FIELD_BUDGET_MIN, max: FIELD_BUDGET_MAX },
  models: Object.fromEntries(
    MODELS.map((m) => {
      const users = BLOCKS.filter((b) => modelKey(b.model) === modelKey(m));
      return [
        modelKey(m),
        {
          blocks: users.map((b) => b.id),
          variants: users.reduce((n, b) => n + b.variants.length, 0),
          paths: Object.fromEntries(
            modelPaths(m.fields).map(({ path, field }) => [
              path,
              {
                type: field.type,
                required: field.required === true,
                places: users.flatMap((b) => drawnBy(b, path).map((p) => `${b.id}#${p.id}`)),
              },
            ]),
          ),
        },
      ];
    }),
  ),
};

const table = (head, rows) =>
  [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");

const markdown = `# Fields summary

Generated by \`scripts/contract.mjs\` from the manifests (\`packages/blocks/src/**/*.block.ts\` and \`src/models\`); \`bun run verify\`
fails when this file is stale. Contract: \`packages/blocks/contract.json\`; schemas: \`packages/blocks/schemas/\`. Rules:
[content-contract.md](./content-contract.md).

Schemas grow with content models, not with variants: ${MODELS.length} models, ${BLOCKS.length} blocks, ${BLOCKS.reduce((n, b) => n + b.variants.length, 0)} variants.

${table(
  ["Model", "Schema", "Blocks", "Variants", "Field budget"],
  MODELS.map((m) => {
    const users = BLOCKS.filter((b) => modelKey(b.model) === modelKey(m));
    return [
      `\`${modelKey(m)}\``,
      `\`${schemaFile(m)}\``,
      users.map((b) => `\`${b.id}\``).join(", "),
      String(users.reduce((n, b) => n + b.variants.length, 0)),
      `${modelPaths(m.fields).length} / ${FIELD_BUDGET_MAX}`,
    ];
  }),
)}

${MODELS.map((m) => {
  const users = BLOCKS.filter((b) => modelKey(b.model) === modelKey(m));
  return `## \`${modelKey(m)}\`

${table(
  ["Path", "Type", "Required", "Label", "Drawn at (block#place)"],
  modelPaths(m.fields).map(({ path, field }) => [
    `\`${path}\``,
    field.type + ("maxLength" in field ? ` ≤ ${field.maxLength}` : "") + (field.type === "list" ? ` of ${field.item.id} (${field.minItems}–${field.maxItems})` : ""),
    field.required ? "yes" : "",
    label(field.label),
    users.flatMap((b) => drawnBy(b, path).map((p) => `\`${b.id}#${p.id}\``)).join(", ") || "—",
  ]),
)}`;
}).join("\n\n")}

## Blocks

${BLOCKS.map((b) => `### \`${b.id}\`

- Category: \`${b.category}\`, label: ${b.label}, model: \`${modelKey(b.model)}\`
- Options (per instance): ${Object.entries(b.options).map(([k, d]) => `\`${k}\` ∈ {${d.values.join(", ")}}, default ${d.default}`).join("; ") || "—"}
- Variants (layout only): ${b.variants.map((v) => `\`${v.id}\`${v.default ? " (default)" : ""} (${Object.entries(v.layout).map(([k, val]) => `${k}=${val}`).join(", ")})`).join(", ")}

${table(
  ["Place", "Role", "Fields", "Repeats over"],
  b.places.map((p) => [`\`${p.id}\``, p.role, p.fields.map((f) => `\`${f}\``).join(" + "), p.each ? `\`${p.each}\`${p.wireframe ? ` (wireframe × ${p.wireframe})` : ""}` : ""]),
)}`).join("\n\n")}
`;

const out = new Map();
const json = (v) => `${JSON.stringify(v, null, 2)}\n`;
for (const m of MODELS) out.set(join("packages/blocks", schemaFile(m)), json(toJsonSchema(m, label)));
out.set("packages/blocks/contract.json", json(contract));
out.set("docs/fields.json", json(fields));
out.set("docs/fields.md", markdown);

const read = (p) => {
  try {
    return readFileSync(join(ROOT, p), "utf8");
  } catch {
    return null;
  }
};

const schemaDir = join(ROOT, "packages/blocks/schemas");
let orphans = [];
try {
  orphans = readdirSync(schemaDir)
    .map((f) => `packages/blocks/schemas/${f}`)
    .filter((p) => !out.has(p));
} catch {}

if (check) {
  const stale = [...out].filter(([p, text]) => read(p) !== text).map(([p]) => p);
  stale.push(...orphans.map((p) => `${p} (orphan)`));
  if (stale.length) {
    console.error(`contract: stale ${stale.join(", ")}. Run \`bun run contract\` and commit.`);
    process.exit(1);
  }
  console.log(`contract: up to date (${out.size} files)`);
  process.exit(0);
}

mkdirSync(schemaDir, { recursive: true });
for (const [p, text] of out) writeFileSync(join(ROOT, p), text);
console.log(`contract: wrote ${[...out.keys()].join(", ")}`);
if (orphans.length) console.warn(`contract: orphan schemas ${orphans.join(", ")}`);
