#!/usr/bin/env node
// Brand presets from codegen-x/ui8kit packages/taste-data (MIT): the owner's curated row 1 (curated.ts CURATED_ROWS, minus
// EXCLUDED_SCREENS / EXCLUDED_SCREENS_2) with each taste's skin, fonts and radius from tastes.ts. Density and shadow are not
// in taste-data: this script derives them from the taste's composition and recipe (rule below, ours). Writes
// packages/theme/src/presets.ts. Usage: node scripts/port-presets.mjs <codegen-x>/packages/taste-data/src
import fs from "node:fs";
import path from "node:path";

const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/port-presets.mjs <codegen-x>/packages/taste-data/src");
const curated = fs.readFileSync(path.join(src, "curated.ts"), "utf8");
const tastes = fs.readFileSync(path.join(src, "tastes.ts"), "utf8");

const row1 = /row:\s*1,\s*keep:\s*\[([\s\S]*?)\]/.exec(curated)[1].match(/"([^"]+)"/g).map((s) => s.slice(1, -1));
const excluded = [...curated.matchAll(/EXCLUDED_SCREENS(?:_2)?: string\[\] = \[([\s\S]*?)\]/g)].flatMap((m) => m[1].match(/"([^"]+)"/g).map((s) => s.slice(1, -1)));
const re = /\{ id: "([^"]+)",\s*skin: "([^"]+)",\s*fonts: \{ display: "([^"]+)",\s*body: "([^"]+)"\s*\}, radius:\s*(\d+), composition: "([^"]+)",\s*recipe: "([^"]+)"/g;
const byId = new Map([...tastes.matchAll(re)].map((m) => [m[1], { id: m[1], skin: m[2], display: m[3], body: m[4], radius: Number(m[5]), composition: m[6], recipe: m[7] }]));

// ours: airy / poster / full-bleed / frame breathe (comfortable), dense-grid / stats pack (compact), the rest default
const density = (c) => (["airy", "poster", "full-bleed", "frame"].includes(c) ? "comfortable" : ["dense-grid", "stats"].includes(c) ? "compact" : null);
// ours: glass (and frame compositions) lift cards and media (md); soft recipes a little (sm); flat ones stay flat (none)
const shadow = (t) => (t.recipe === "glass" || t.composition === "frame" ? "md" : ["mesh", "conic", "rings", "dots"].includes(t.recipe) ? "sm" : "none");

const presets = row1
  .filter((id) => !excluded.includes(id))
  .map((id) => {
    const t = byId.get(id);
    if (!t) throw new Error("no taste " + id);
    const d = density(t.composition);
    const s = shadow(t);
    const tokens = {
      ...(d ? { "density-badge": d, "density-button": d, "density-card": d, "density-alert": d } : {}),
      "shadow-card": s,
      "shadow-alert": s,
      "shadow-media": s,
    };
    return { id, skin: t.skin, font: t.body, headingFont: t.display, radius: t.radius, tokens, composition: t.composition, recipe: t.recipe };
  });

const out = `// Generated by scripts/port-presets.mjs from codegen-x/ui8kit packages/taste-data (MIT): the owner's curated row 1.
// skin, fonts and radius are the taste's own; density and shadow are derived from its composition and recipe by our rule
// (see the script). Each preset is a codegen-x theme (magazine-theme v2 fields): one click applies it, export carries it there.
import type { Tokens } from "./design";

export type Preset = {
  id: string;
  skin: string;
  font: string;
  headingFont: string;
  radius: number;
  tokens: Tokens;
  composition: string;
  recipe: string;
};

export const PRESETS_ROW1: Preset[] = ${JSON.stringify(presets, null, 2)};
`;
fs.writeFileSync(path.resolve("packages/theme/src/presets.ts"), out);
console.log(`presets.ts: ${presets.length} presets`);
