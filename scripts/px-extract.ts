/**
 * ui8px inputs that are not already HTML or CSS (`bun run px:extract`, run by the gate):
 *
 * - `.ui8px/extract/classes.html`: every class string of `packages/blocks/src/classes.ts` (the hand-written utilities),
 *   read by importing the module, so template literals and composed strings are what the app really uses;
 * - `.ui8px/extract/density.css`: every per-element density step of `packages/theme` (`densityVars`, `DENSITY_PX`) as the
 *   CSS the shapes get (`tokens.css`: --h-* / --w-* -> height / width, --pad-card -> padding), so `validate grid` checks
 *   the px values (badge steps under the controls scope, `.ui8px/policy/scopes.json`).
 *
 * The generated wireframes are linted as rendered (`packages/blocks/catalog/wireframes.snap.html`, checked against the
 * live render by vitest), never by scanning their source.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import * as classes from "../packages/blocks/src/classes";
import { densityVars } from "../packages/theme/src/css";
import { DENSITIES, setDensity } from "../packages/theme/src/design";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, ".ui8px", "extract");

function leaves(value: unknown, at: string, out: Array<[string, string]>): Array<[string, string]> {
  if (typeof value === "string") out.push([at, value]);
  else if (value && typeof value === "object") for (const [k, v] of Object.entries(value)) leaves(v, `${at}.${k}`, out);
  return out;
}

function fail(message: string): never {
  throw new Error(`px:extract: ${message}`);
}
const escape = (s: string) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const lists = Object.entries(classes).flatMap(([name, v]) => leaves(v, name, []));
const html = [
  "<!doctype html>",
  "<!-- generated by scripts/px-extract.ts from packages/blocks/src/classes.ts; do not edit -->",
  "<html><body>",
  ...lists.map(([at, cls]) => `<i data-src="classes.ts#${escape(at)}" class="${escape(cls)}"></i>`),
  "</body></html>",
  "",
].join("\n");

/** the shape selector and property of each density variable (packages/blocks/src/tokens.css) */
const TARGET: Record<string, [string, string]> = {
  "--h-button": ['[data-shape="cta"][data-slot="button"]', "height"],
  "--w-button": ['[data-shape="cta"][data-slot="button"]', "width"],
  "--h-badge": ['[data-shape="badge"][data-slot="badge"]', "height"],
  "--w-badge": ['[data-shape="badge"][data-slot="badge"]', "width"],
  "--pad-card": ['[data-role="surface"][data-slot="card"]', "padding"],
};
const css: string[] = ["/* generated by scripts/px-extract.ts from packages/theme densityVars; do not edit */"];
for (const density of DENSITIES) {
  const rules = new Map<string, string[]>();
  for (const [name, value] of Object.entries(densityVars(setDensity({}, density)))) {
    const [shape, property] = TARGET[name] ?? fail(`no shape target for ${name} (add it to TARGET)`);
    const selector = `${shape}[data-density="${density}"]`;
    rules.set(selector, [...(rules.get(selector) ?? []), `${property}: ${value};`]);
  }
  for (const [selector, decls] of rules) css.push(`${selector} { ${decls.join(" ")} }`);
}

mkdirSync(OUT, { recursive: true });
writeFileSync(path.join(OUT, "classes.html"), html);
writeFileSync(path.join(OUT, "density.css"), `${css.join("\n")}\n`);
console.log(`px:extract: ${lists.length} class lists (classes.ts), ${css.length - 1} density rules`);
